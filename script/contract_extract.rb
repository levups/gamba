# frozen_string_literal: true

# Writes test/contract/prawn-2.5.0.yml: every public method of the classes users touch, with its parameters and
# the YARD group Prawn files it under (Stable, Experimental, Extension). Runs under the reference engine:
#   BUNDLE_GEMFILE=oracle/Gemfile bundle exec ruby script/contract_extract.rb

require "prawn"
require "prawn/table"
require "prawn-svg"
require "yaml"

CLASS_NAMES = %w[
  Prawn::Document
  Prawn::Document::BoundingBox
  Prawn::Document::ColumnBox
  Prawn::Font
  Prawn::Outline
  Prawn::Text::Box
  Prawn::Text::Formatted::Box
  Prawn::View
].freeze
# prawn-table and prawn-svg have no YARD groups: their whole public API is their contract.
PLUGIN_CLASS_NAMES = %w[
  Prawn::Table
  Prawn::Table::Interface
  Prawn::Table::Cells
  Prawn::Table::Cell
  Prawn::Table::Cell::Text
  Prawn::Table::Cell::Image
  Prawn::Table::Cell::Subtable
  Prawn::Table::Cell::SpanDummy
  Prawn::SVG::Interface
  Prawn::SVG::Extension
].freeze
OWNER_NAMESPACES = /\A(Prawn|PDF::Core)::/

def group_of(file, line)
  File.readlines(file).first(line).reverse_each do |source_line|
    return "Ungrouped" if source_line.match?(/^\s*# @endgroup/)
    return source_line[/# @group (.+)/, 1].strip if source_line.include?("# @group ")
  end
  "Ungrouped"
end

def private_in_yard?(file, line)
  File.readlines(file)[0...(line - 1)].reverse.take_while { |line| line.match?(/^\s*#/) }.any? { |comment| comment.match?(/@private|:nodoc:/) }
end

# Forwardable's delegators take (*args, &block): the signature that counts is the one of the method they call.
def parameters_of(method)
  return method.parameters unless method.source_location.first.end_with?("forwardable.rb")

  Prawn::Document.new.renderer.method(method.name).parameters
end

def describe(method)
  file, line = method.source_location
  {"parameters" => parameters_of(method).map { |kind, name| "#{kind} #{name}".strip }, "group" => group_of(file, line)}
    .merge(private_in_yard?(file, line) ? {"yard_private" => true} : {})
end

def contract_for(class_names, group: nil)
  class_names.to_h do |class_name|
    klass = Object.const_get(class_name)
    instance_methods = klass.is_a?(Class) ? klass.public_instance_methods : klass.public_instance_methods(false)
    methods = instance_methods.map { klass.instance_method(_1) }.select { |method| method.owner.name&.match?(OWNER_NAMESPACES) && method.source_location }
    singleton_methods = klass.singleton_methods.map { klass.method(_1) }.select { |method| method.owner.inspect.match?(/Prawn|PDF::Core/) && method.source_location }
    entries = methods.sort_by(&:name).to_h { |method| ["##{method.name}", describe(method)] }
    entries.merge!(singleton_methods.sort_by(&:name).to_h { |method| [".#{method.name}", describe(method)] })
    entries.transform_values! { _1.merge("group" => group) } if group
    [class_name, entries]
  end
end

{
  "prawn-#{Prawn::VERSION}" => contract_for(CLASS_NAMES),
  "prawn-table-#{Gem.loaded_specs.fetch("prawn-table").version}-prawn-svg-#{Prawn::SVG::VERSION}" => contract_for(PLUGIN_CLASS_NAMES, group: "Stable API")
}.each do |name, contract|
  path = File.expand_path("../test/contract/#{name}.yml", __dir__)
  File.write(path, "# Generated by script/contract_extract.rb: do not edit.\n#{contract.to_yaml}")
  puts "#{path}: #{contract.sum { _1.last.size }} methods"
end
